import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

export async function checkBuildReuse(server) {
  const { simulatorInputSignature: signature, rememberSimulatorBuild: remember, reusableSimulatorCatalog: reuse, forgetSimulatorBuild: forget } = await server.ssrLoadModule('/server/simulatorBuildCache.ts')
  const { saveCatalog, invalidateCatalog, cachedCatalog } = await server.ssrLoadModule('/server/protocolCatalog.ts')
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'aquasim-build-reuse-')))
  const home = path.join(root, 'home'), alias = path.join(root, 'alias')
  fs.mkdirSync(path.join(home, 'src/aqua-sim-tg'), { recursive: true })
  fs.mkdirSync(path.join(home, 'scratch')); fs.mkdirSync(path.join(home, 'cmake-cache')); fs.mkdirSync(path.join(home, 'build/lib'), { recursive: true })
  fs.symlinkSync(home, alias)
  const header = path.join(home, 'src/aqua-sim-tg/custom.h'), cache = path.join(home, 'cmake-cache/CMakeCache.txt'), lib = path.join(home, 'build/lib/libns3-aqua.so')
  const config = 'build_profile:INTERNAL=debug\nCMAKE_GENERATOR:INTERNAL=Ninja\nNS3_WARNINGS_AS_ERRORS:BOOL=OFF\n'
  fs.writeFileSync(path.join(home, 'ns3'), '#!/bin/sh\nexit 0\n', { mode: 0o755 })
  fs.writeFileSync(header, 'version 1'); fs.writeFileSync(cache, config); fs.writeFileSync(lib, 'built binary')
  const layers = saveCatalog(home, 'AQUASIM_CATALOG_BEGIN\n' + JSON.stringify([{ layer: 'mac', typeId: 'ns3::FixtureMac', attributes: [] }]) + '\nAQUASIM_CATALOG_END')
  const persistedLayers = JSON.parse(JSON.stringify(layers))
  try {
    assert.equal(reuse(home), null, 'existing files alone are not evidence of a successful build')
    const baseline = signature(home)
    assert.ok(baseline)
    remember(home, baseline, layers)
    assert.deepEqual(reuse(home), persistedLayers)
    invalidateCatalog(home)
    assert.equal(cachedCatalog(home), null)
    assert.deepEqual(reuse(alias), persistedLayers, 'persistent snapshot restores catalog after process-memory cache loss and canonicalizes paths')
    assert.deepEqual(cachedCatalog(home), persistedLayers)
    fs.utimesSync(header, new Date(), new Date())
    assert.deepEqual(reuse(home), persistedLayers, 'touching identical input content does not require rebuilding')
    fs.writeFileSync(header, 'version 2')
    assert.equal(reuse(home), null, 'same-length source edits invalidate without waiting for library rebuild')
    fs.writeFileSync(header, 'version 1')
    fs.writeFileSync(path.join(home, 'src/aqua-sim-tg/new.cc'), 'new registered class')
    assert.equal(reuse(home), null, 'new source files invalidate')
    fs.rmSync(path.join(home, 'src/aqua-sim-tg/new.cc'))
    fs.writeFileSync(path.join(home, 'scratch/aqua-visual-example.cc'), 'generated probe/run')
    assert.deepEqual(reuse(home), persistedLayers, 'temporary platform programs do not invalidate the baseline')
    fs.writeFileSync(cache, config + 'CUSTOM_BUILD_FLAG:BOOL=ON\n')
    assert.equal(reuse(home), null, 'configuration changes invalidate')
    fs.writeFileSync(cache, config)
    fs.rmSync(lib)
    assert.equal(reuse(home), null, 'missing library outputs cannot be reused')
    fs.writeFileSync(lib, 'rebuilt binary')
    assert.equal(reuse(home), null, 'externally rebuilt outputs require renewed verification')
    remember(home, signature(home), layers)
    assert.deepEqual(reuse(home), persistedLayers)
    forget(home)
    assert.equal(reuse(home), null, 'clean/build start removes last known success before a possible failure')
    const before = signature(home)
    fs.writeFileSync(header, 'version 3')
    remember(home, before, layers)
    assert.equal(reuse(home), null, 'source changes during compilation never create a trusted reusable result')
    fs.writeFileSync(cache, config.replace('OFF', 'ON'))
    assert.equal(signature(home), null, 'Werror repair still requires the normal configure/build path')
  } finally { forget(home); invalidateCatalog(home); fs.rmSync(root, { recursive: true, force: true }) }
  console.log('Build reuse regressions passed: persistent real catalog, content fingerprints, configuration/artifact/source invalidation, aliases, touched files, failed builds and changed-during-build protection.')
}
