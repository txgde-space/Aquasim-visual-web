// Export the SAME trace/serialization implementation used by generated Web runs.
// This tool never configures, builds, or edits an external ns-3 tree.
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = fileURLToPath(new URL('..', import.meta.url))
const destination = path.join(root, 'contrib/visual-logger')
const cacheDir = mkdtempSync(path.join(tmpdir(), 'aquasim-logger-export-'))
const server = await createServer({ root, configFile: false, cacheDir,
  server: { middlewareMode: true, hmr: false, ws: false, watch: null },
  optimizeDeps: { noDiscovery: true, include: [] }, appType: 'custom', logLevel: 'error' })
const replaceOnce = (text, before, after) => {
  assert.equal(text.split(before).length, 2, `Trace template changed; review export adapter: ${before}`)
  return text.replace(before, after)
}
try {
  const { REPLAY_TRACE_CC } = await server.ssrLoadModule('/src/features/experiment/lib/replayTrace.ts')
  const { MOBILITY_TRACE_CC } = await server.ssrLoadModule('/src/features/experiment/lib/mobilityTrace.ts')
  const { PHY_PACKET_TIMING_CC } = await server.ssrLoadModule('/src/features/experiment/lib/phyPacketTiming.ts')
  const { OBSERVED_SIGNAL_CACHE_CC } = await server.ssrLoadModule('/src/features/experiment/lib/observedSignalCache.ts')
  let trace = replaceOnce(REPLAY_TRACE_CC,
    'static void VisualTxTrace(uint32_t id, Ptr<AquaSimPhy> phy, Ptr<Packet> packet, double noise) {\n    auto copy = packet->Copy();\n    AquaSimPacketStamp stamp; copy->RemoveHeader(stamp);\n    auto durationNs = phy->calcTxTime(copy).GetNanoSeconds();',
    `static void VisualTxTrace(uint32_t id, Time duration, Ptr<Packet> packet) {
    if (!packet || duration.GetNanoSeconds() < 0) throw std::runtime_error("Invalid transmission");
    if (visualPackets.size() >= 30000) throw std::runtime_error("Replay exceeds 30000 transmissions; shorten the run");
    const auto durationNs = duration.GetNanoSeconds();`)
  const start = trace.indexOf('static void VisualConnectReceptionEvents(')
  const end = trace.indexOf('static void WriteVisualPackets(')
  assert.ok(start >= 0 && end > start)
  trace = trace.slice(0, start) + trace.slice(end)
  // One receiver serializer serves both network packets and node-owned RX events.
  const rxStart = trace.indexOf('            const auto& rx = tx.receivers[j];')
  const rxEnd = trace.indexOf("            output << '}';", rxStart) + "            output << '}';".length
  assert.ok(rxStart >= 0 && rxEnd > rxStart)
  const receiverWriter = `static void WriteVisualReceiver(std::ostream& output, const VisualRx& rx) {\n${trace.slice(rxStart, rxEnd)
    .replace('            const auto& rx = tx.receivers[j];\n', '').replace(/^            /gm, '    ')}\n}\n`
  trace = trace.slice(0, rxStart) + '            WriteVisualReceiver(output, tx.receivers[j]);' + trace.slice(rxEnd)
  trace = trace.replace('static void WriteVisualPackets(', receiverWriter + 'static void WriteVisualPackets(')
  trace = replaceOnce(trace,
    'return info.callback == contract && source->TraceConnectWithoutContext(name, callback);',
    `{
                if (info.callback != contract || !source->TraceConnectWithoutContext(name, callback)) return false;
                connections.push_back({source, name, callback});
                return true;
            }`)
  const withoutIncludes = text => text.replace(/^#include .*\n/gm, '')
  // Permit node-owned trajectory output without duplicating trajectories on merge.
  let mobility = replaceOnce(MOBILITY_TRACE_CC,
    'static void WriteVisualMovements(std::ostream& output) {',
    'static void WriteVisualMovements(std::ostream& output, int64_t owner = -1) {')
  mobility = replaceOnce(mobility,
    "    for (size_t i = 0; i < visualMovements.size(); ++i) {\n        if (i) output << ',';\n        const auto& movement = visualMovements[i];",
    "    bool first = true;\n    for (size_t i = 0; i < visualMovements.size(); ++i) {\n        const auto& movement = visualMovements[i];\n        if (owner >= 0 && movement.nodeId != static_cast<uint32_t>(owner)) continue;\n        if (!first) output << ',';\n        first = false;")
  const generated = `// Generated by node scripts/export-ns3-logger.mjs; do not edit.\n#pragma once\n${PHY_PACKET_TIMING_CC}
namespace ns3 { namespace visual_logger_detail {
struct Connection { Ptr<Object> source; std::string name; CallbackBase callback; };
static std::vector<Connection> connections;
${withoutIncludes(trace)}
${withoutIncludes(mobility)}
} } // namespace ns3::visual_logger_detail
`
  const cache = `// Optional adapter for the IncomingPacket/heads cache API ONLY.\n// Generated by node scripts/export-ns3-logger.mjs; do not edit.\n#pragma once\n#include "ns3/aqua-sim-phy.h"\n#include "ns3/aqua-sim-net-device.h"\n#include "ns3/aqua-sim-signal-cache.h"\n${OBSERVED_SIGNAL_CACHE_CC.replace('#include "ns3/aqua-sim-tg-module.h"', '')}`
  mkdirSync(destination, { recursive: true })
  for (const [name, text] of [['model/detail/trace-core.h', generated], ['adapters/observed-cache.h', cache]]) {
    const file = path.join(destination, name)
    mkdirSync(path.dirname(file), { recursive: true })
    if (process.argv.includes('--check')) assert.equal(readFileSync(file, 'utf8'), text, `Regenerate ${file}`)
    else writeFileSync(file, text)
  }
  console.log(process.argv.includes('--check') ? 'Portable trace matches Web source.' : `Exported trace to ${destination}`)
} finally {
  await server.close()
  rmSync(cacheDir, { recursive: true, force: true })
}
